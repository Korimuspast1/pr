package com.zalchik.grust.data

import java.time.LocalDate

/**
 * The text the app says to the user, and the questions it asks.
 *
 * Picked by the day rather than at random: a phrase that changes on every recomposition would look
 * like a glitch, and a phrase that changes day by day gives a reason to come back.
 */
object Words {

    val support = listOf(
        "Грусть - это не поломка. Это погода, и она проходит.",
        "Ты дошёл до сегодняшнего дня. Этого уже достаточно.",
        "Не обязательно быть в порядке, чтобы быть в порядке.",
        "Плохой день - не плохая жизнь.",
        "То, что ты чувствуешь, имеет право быть.",
        "Медленно - это тоже движение.",
        "Ты не обязан объяснять свою грусть, чтобы её уважали.",
        "Иногда всё, что можно сделать, - переждать. Это тоже работа.",
        "Слёзы - это не слабость, а способ выпустить давление.",
        "Ты не один в этой тишине.",
        "Даже если сегодня только «дожить до вечера» - это достойная цель.",
        "Ты уже переживал дни, которые казались непереживаемыми.",
        "Не сравнивай свою изнанку с чужой обложкой.",
        "Позаботиться о себе - не эгоизм, а топливо.",
        "Усталость - не лень. Дай себе сесть.",
        "Завтра не обязано быть лучше. Но оно будет другим.",
        "Пиши, даже если выходит криво. Криво - это честно.",
        "Ты имеешь право на плохой вечер и на тёплый плед.",
        "Ничего страшного, если сегодня получилось только дышать.",
        "То, что ты здесь и пытаешься, - уже смелость.",
    )

    val prompts = listOf(
        "Что сейчас тяжелее всего?",
        "Что бы ты сказал другу в такой же ситуации?",
        "Какой момент дня был самым тихим?",
        "Что помогло бы на один процент?",
        "Чего тебе сейчас не хватает?",
        "За что ты можешь себя тихо поблагодарить?",
        "Что ты несёшь с собой, хотя уже можно положить?",
        "Какая мелочь сегодня была тёплой?",
    )

    fun supportOfDay(day: LocalDate): String = pick(support, day)

    fun promptOfDay(day: LocalDate): String = pick(prompts, day)

    private fun pick(lines: List<String>, day: LocalDate): String =
        lines[Math.floorMod(day.toEpochDay(), lines.size.toLong()).toInt()]
}
