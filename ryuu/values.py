"""Специфические для RYU типы значений."""


class Link(str):
    """Ссылка (руна ``&``) — URI/URL/путь.

    Подкласс ``str``: ведёт себя как обычная строка, но сериализуется
    обратно руной ``&``, а не ``~``.
    """

    __slots__ = ()

    def __repr__(self):
        return f"Link({str.__repr__(self)})"
