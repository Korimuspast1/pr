#!/usr/bin/env python3
"""Write a local ``API_KEYS`` file for an AyuGram4A build.

``TMessagesProj/build.gradle`` reads ``API_KEYS`` from the project root:

    buildConfigField 'int', 'APP_ID', localProperties.getProperty("APP_ID")
    buildConfigField 'String', 'APP_HASH', localProperties.getProperty("APP_HASH")

That file is listed in the repository's ``.gitignore`` — it must never be
committed. This helper writes it with the right permissions and refuses to run
inside a git work tree unless the path is ignored, so a key cannot leak by
accident.

Usage
-----
    # from a file you keep outside the repository
    python3 ayuox4gg/tools/setup_keys.py --app-id 12345 --app-hash abcdef... --output /path/to/AyuGram4A/API_KEYS

    # or interactively (values are not echoed)
    python3 ayuox4gg/tools/setup_keys.py --ask --output /path/to/AyuGram4A/API_KEYS

    # check an existing file without printing the secrets
    python3 ayuox4gg/tools/setup_keys.py --check /path/to/AyuGram4A/API_KEYS
"""

from __future__ import annotations

import argparse
import getpass
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Dict, Optional

APP_HASH_RE = re.compile(r"^[0-9a-fA-F]{32}$")
APP_ID_RE = re.compile(r"^\d{1,10}$")


def parse_existing(path: Path) -> Dict[str, str]:
    values: Dict[str, str] = {}
    if not path.is_file():
        return values
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip().strip('"')
    return values


def validate(app_id: str, app_hash: str) -> Optional[str]:
    if not APP_ID_RE.match(app_id):
        return "APP_ID must be a number (1-10 digits)"
    if not APP_HASH_RE.match(app_hash):
        return "APP_HASH must be 32 hex characters"
    return None


def is_git_ignored(path: Path) -> bool:
    """True when git would ignore ``path`` (works for files and bare .git dirs)."""
    try:
        result = subprocess.run(
            ["git", "check-ignore", "-q", "--no-index", "--", str(path)],
            cwd=str(path.parent), capture_output=True,
        )
        return result.returncode == 0
    except OSError:
        return False


def write_file(path: Path, app_id: str, app_hash: str, maps_key: str = "",
               sign_password: str = "", sign_alias: str = "") -> None:
    lines = [
        "# Generated by ayuox4gg/tools/setup_keys.py — NEVER commit this file.",
        "# Create your own pair at https://my.telegram.org -> API development tools",
        "APP_ID = {}".format(app_id),
        'APP_HASH = "{}"'.format(app_hash),
        'MAPS_V2_API = "{}"'.format(maps_key),
        "",
        "# Optional: only needed for a signed release build.",
        'SIGNING_KEY_PASSWORD = "{}"'.format(sign_password),
        'SIGNING_KEY_ALIAS = "{}"'.format(sign_alias),
        'SIGNING_KEY_STORE_PASSWORD = "{}"'.format(sign_password),
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass


def redact(value: str) -> str:
    if not value:
        return "(empty)"
    if len(value) <= 6:
        return "*" * len(value)
    return value[:3] + "*" * (len(value) - 6) + value[-3:]


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description="Create or inspect a local API_KEYS file (git-ignored, chmod 600).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--app-id", help="Telegram api_id (digits)")
    parser.add_argument("--app-hash", help="Telegram api_hash (32 hex chars)")
    parser.add_argument("--maps-key", default="", help="Google Maps API key (optional)")
    parser.add_argument("--sign-password", default="", help="keystore password (optional)")
    parser.add_argument("--sign-alias", default="", help="keystore alias (optional)")
    parser.add_argument("--output", help="path of the API_KEYS file to write")
    parser.add_argument("--ask", action="store_true", help="prompt for the values without echoing")
    parser.add_argument("--check", metavar="PATH", help="print a redacted summary of an existing file")
    parser.add_argument("--force", action="store_true", help="write even if the path is not git-ignored")
    args = parser.parse_args(argv)

    if args.check:
        path = Path(args.check)
        values = parse_existing(path)
        if not values:
            print("ERROR: no readable API_KEYS at {}".format(path), file=sys.stderr)
            return 2
        print("file      : {}".format(path))
        print("APP_ID    : {}".format(values.get("APP_ID", "(missing)")))
        print("APP_HASH  : {}".format(redact(values.get("APP_HASH", ""))))
        print("MAPS key  : {}".format(redact(values.get("MAPS_V2_API", ""))))
        print("signing   : {}".format("set" if values.get("SIGNING_KEY_PASSWORD") else "(none)"))
        problem = validate(values.get("APP_ID", ""), values.get("APP_HASH", ""))
        print("valid     : {}".format("yes" if problem is None else problem))
        return 0 if problem is None else 1

    app_id = args.app_id
    app_hash = args.app_hash
    if args.ask:
        app_id = input("api_id: ").strip()
        app_hash = getpass.getpass("api_hash (hidden): ").strip()

    if not app_id or not app_hash:
        parser.error("pass --app-id/--app-hash, or use --ask")
    problem = validate(app_id.strip(), app_hash.strip())
    if problem:
        print("ERROR: " + problem, file=sys.stderr)
        return 1

    output = Path(args.output or "API_KEYS").resolve()
    if not args.force and output.parent.joinpath(".git").exists() and not is_git_ignored(output):
        print(
            "REFUSING: {} is inside a git work tree and not ignored.\n"
            "Add it to .gitignore (AyuGram4A ignores 'API_KEYS' already) or pass --force.".format(output),
            file=sys.stderr,
        )
        return 1

    write_file(output, app_id.strip(), app_hash.strip(), args.maps_key,
               args.sign_password, args.sign_alias)
    print("wrote {} (mode 600, git-ignored by the upstream repository)".format(output))
    print("APP_ID   = {}".format(app_id.strip()))
    print("APP_HASH = {}".format(redact(app_hash.strip())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
