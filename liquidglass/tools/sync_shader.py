#!/usr/bin/env python3
"""
Regenerates app/src/main/java/dev/arena/liquidglasslab/Shaders.java from
shader/liquid_glass.sksl so the shipped AGSL string and the offline reference
renderer can never drift apart.

Run after every shader edit:   python3 tools/sync_shader.py
Check in CI / locally:         python3 tools/sync_shader.py --check
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SKS = os.path.join(ROOT, "shader", "liquid_glass.sksl")
JAVA = os.path.join(ROOT, "app", "src", "main", "java", "dev", "arena",
                    "liquidglasslab", "Shaders.java")


def java_body(src: str) -> str:
    lines = []
    # strip comment-only lines: they carry no meaning for the AGSL compiler and
    # would only bloat the Java string
    for raw in src.splitlines():
        line = raw.split("//")[0].rstrip() if not raw.strip().startswith("//") else ""
        if line:
            lines.append(line)
    out = []
    for line in lines:
        esc = line.replace("\\", "\\\\").replace('"', '\\"')
        out.append('            + "%s\\n"' % esc)
    return "\n".join(out)


TEMPLATE = '''package dev.arena.liquidglasslab;

/**
 * The AGSL sources shipped with the app.
 *
 * <p>{@link #LIQUID_GLASS} is the exact same shader that
 * {@code shader/liquid_glass.sksl} holds and that {@code tools/skialab.py} renders
 * offline. It is generated by {@code tools/sync_shader.py} — never edit by hand.
 */
public final class Shaders {

    public static final String KEY = "liquid_glass";

    private Shaders() {
    }

    public static final String LIQUID_GLASS = ""
{body};
}
'''


def main() -> int:
    src = open(SKS, "r", encoding="utf-8").read()
    generated = TEMPLATE.replace("{body}", java_body(src))
    if "--check" in sys.argv:
        current = open(JAVA, "r", encoding="utf-8").read() if os.path.exists(JAVA) else ""
        if current != generated:
            print("Shaders.java is out of date; run tools/sync_shader.py")
            return 1
        print("Shaders.java is in sync with shader/liquid_glass.sksl")
        return 0
    with open(JAVA, "w", encoding="utf-8") as fh:
        fh.write(generated)
    print("wrote", os.path.relpath(JAVA, ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
