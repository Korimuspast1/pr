function endingFor(G) {
  if (G.player.infect >= 100) return ENDINGS.infected;
  const alive = G.group.filter(n => !n.dead).length;
  const total = G.group.length + 1;
  if (G.stats.died || alive === 0) return ENDINGS.alone;
  if (alive >= total - 1 && G.trust >= 70 && G.flags.goodMan) return ENDINGS.good;
  return ENDINGS.mixed;
}

