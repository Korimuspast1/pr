import { createCanvas, loadImage } from '@napi-rs/canvas';
import { writeFile } from 'node:fs/promises';
const [srcPath, x0, y0, w, h, scale, name] = process.argv.slice(2);
const src = await loadImage(new URL('../shots/' + srcPath, import.meta.url));
const c = createCanvas(w * scale, h * scale);
const g = c.getContext('2d');
g.imageSmoothingEnabled = false;
g.drawImage(src, +x0, +y0, +w, +h, 0, 0, w * scale, h * scale);
await writeFile(new URL('../shots/' + name, import.meta.url), c.toBuffer('image/png'));
console.log('ok');
