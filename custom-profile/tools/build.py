#!/usr/bin/env python3
"""Build and validate the installable Custom Profile ``.elyx`` archive.

Run from anywhere::

    python3 custom-profile/tools/build.py              # rebuild + verify
    python3 custom-profile/tools/build.py --check      # verify committed archive
    python3 custom-profile/tools/build.py --no-manifest  # skip digest manifest

What the build guarantees
-------------------------
* all modules are syntax-checked (``compile()``) before packaging;
* every source file is parsed with :mod:`ast`, so accidental use of Python
  3.12+ syntax (walrus in comprehensions, ``except*``, …) fails the build even
  though the host runs Python 3.11;
* the archive root contains ``refmap.yml``/``metainfo.yml``/``main.py`` and no
  wrapper directory, as Elyx requires;
* a SHA-256 ``manifest.py`` is generated *inside* the archive so the plugin can
  verify its own files at load time (see ``verify.py``);
* identical inputs produce identical archives: ZIP timestamps and permissions
  are normalised, which makes reproducible builds and diffable releases easy;
* the final SHA-256 of the archive is printed and, with ``--write-sums``, stored
  next to the release as ``custom-profile.elyx.sha256``.
"""

from __future__ import annotations

import argparse
import ast
import hashlib
import py_compile
import sys
import tempfile
import zipfile
from pathlib import Path
from typing import Dict, Iterable, Tuple

PROJECT = Path(__file__).resolve().parents[1]
REPOSITORY = PROJECT.parent
ARCHIVE = REPOSITORY / "release" / "custom-profile.elyx"
CHECKSUM_FILE = ARCHIVE.with_suffix(ARCHIVE.suffix + ".sha256")

#: Files copied into the archive, in a stable order.
FILES: Tuple[str, ...] = (
    "refmap.yml",
    "metainfo.yml",
    "main.py",
    "core.py",
    "verify.py",
    "README.md",
    "LICENSE",
    "strings/strings_en.yml",
    "strings/strings_ru.yml",
)

#: Python modules that are hashed into the manifest.
PYTHON_FILES: Tuple[str, ...] = ("main.py", "core.py", "verify.py")

REQUIRED_ROOT = {"refmap.yml", "metainfo.yml", "main.py"}
WRAPPED_PREFIXES = ("custom-profile/", "./")
#: The host runs CPython 3.11; keep generated bytecode in mind when bumping.
TARGET_FEATURE_VERSION = (3, 11)
FIXED_DATE_TIME = (2020, 1, 1, 0, 0, 0)


# ---------------------------------------------------------------------------
# Source validation
# ---------------------------------------------------------------------------
def python_sources() -> Iterable[Path]:
    for path in sorted(PROJECT.rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        yield path


def validate_sources() -> None:
    missing = [relative for relative in FILES if not (PROJECT / relative).is_file()]
    if missing:
        raise RuntimeError("Missing package source file(s): " + ", ".join(missing))

    for path in python_sources():
        source = path.read_text(encoding="utf-8")
        relative = path.relative_to(PROJECT)
        try:
            compile(source, str(path), "exec")
        except SyntaxError as error:
            raise RuntimeError("Syntax error in {}: {}".format(relative, error)) from error
        try:
            ast.parse(source, filename=str(path), feature_version=TARGET_FEATURE_VERSION)
        except SyntaxError as error:
            raise RuntimeError(
                "{} is not valid Python {}.{}: {}".format(
                    relative, TARGET_FEATURE_VERSION[0], TARGET_FEATURE_VERSION[1], error
                )
            ) from error
        # Byte-compile into a temporary directory: this mirrors what the host
        # does and catches issues that only appear at compile time.
        with tempfile.TemporaryDirectory() as tmp:
            py_compile.compile(str(path), cfile=str(Path(tmp) / "out.pyc"), doraise=True)


# ---------------------------------------------------------------------------
# Manifest
# ---------------------------------------------------------------------------
def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def build_manifest() -> bytes:
    """Return the generated ``manifest.py`` module as UTF-8 bytes."""
    entries: Dict[str, str] = {}
    for relative in PYTHON_FILES:
        entries[relative] = sha256_bytes((PROJECT / relative).read_bytes())
    lines = [
        '"""Generated by tools/build.py — do not edit.',
        "",
        "SHA-256 digests of the Python modules shipped in this archive.",
        "verify.py compares the installed files with these values at load time.",
        '"""',
        "",
        "FILES = {",
    ]
    for relative in PYTHON_FILES:
        lines.append('    {!r}: {!r},'.format(relative, entries[relative]))
    lines.append("}")
    lines.append("")
    return "\n".join(lines).encode("utf-8")


# ---------------------------------------------------------------------------
# Build
# ---------------------------------------------------------------------------
def _normalised_info(name: str) -> zipfile.ZipInfo:
    info = zipfile.ZipInfo(name, date_time=FIXED_DATE_TIME)
    info.external_attr = (0o644 & 0xFFFF) << 16
    info.compress_type = zipfile.ZIP_DEFLATED
    return info


def build(with_manifest: bool = True) -> Path:
    validate_sources()
    ARCHIVE.parent.mkdir(parents=True, exist_ok=True)
    manifest = build_manifest() if with_manifest else None

    with zipfile.ZipFile(ARCHIVE, "w", compression=zipfile.ZIP_DEFLATED) as package:
        # Directory records make strict Elyx archive readers happy.
        package.writestr(_normalised_info("strings/"), b"")
        for relative in FILES:
            package.writestr(_normalised_info(relative), (PROJECT / relative).read_bytes())
        if manifest is not None:
            package.writestr(_normalised_info("manifest.py"), manifest)
    return ARCHIVE


# ---------------------------------------------------------------------------
# Verification
# ---------------------------------------------------------------------------
def validate_archive() -> str:
    if not ARCHIVE.is_file():
        raise RuntimeError("Archive does not exist: {}".format(ARCHIVE))
    with zipfile.ZipFile(ARCHIVE) as package:
        names = set(package.namelist())
        missing = REQUIRED_ROOT - names
        if missing:
            raise RuntimeError("Archive is missing required root file(s): " + ", ".join(sorted(missing)))
        for prefix in WRAPPED_PREFIXES:
            if any(name.startswith(prefix) for name in names):
                raise RuntimeError("Archive contains an invalid wrapper directory: " + prefix)
        if package.read("refmap.yml") != (PROJECT / "refmap.yml").read_bytes():
            raise RuntimeError("Archive refmap.yml does not match source")
        if package.read("metainfo.yml") != (PROJECT / "metainfo.yml").read_bytes():
            raise RuntimeError("Archive metainfo.yml does not match source")
        for relative in PYTHON_FILES:
            if package.read(relative) != (PROJECT / relative).read_bytes():
                raise RuntimeError("Archive {} does not match source".format(relative))
        if "manifest.py" in names:
            # The manifest inside the archive must describe the files inside the
            # archive, not whatever happens to be on disk while checking.
            namespace: Dict[str, object] = {}
            exec(package.read("manifest.py").decode("utf-8"), namespace)  # noqa: S102 - our own file
            recorded = namespace.get("FILES") or {}
            if not isinstance(recorded, dict) or not recorded:
                raise RuntimeError("Archive manifest.py is malformed")
            for relative, expected in recorded.items():
                actual = sha256_bytes(package.read(relative))
                if actual != expected:
                    raise RuntimeError(
                        "Archive manifest mismatch for {}: {} != {}".format(relative, actual, expected)
                    )
        bad = package.testzip()
        if bad:
            raise RuntimeError("Corrupt ZIP entry: " + bad)
    return sha256_bytes(ARCHIVE.read_bytes())


def write_checksum(digest: str) -> Path:
    CHECKSUM_FILE.write_text(
        "{}  {}\n".format(digest, ARCHIVE.name), encoding="utf-8"
    )
    return CHECKSUM_FILE


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="validate the existing archive without rebuilding")
    parser.add_argument("--no-manifest", action="store_true", help="build without the SHA-256 manifest")
    parser.add_argument("--write-sums", action="store_true", help="write release/custom-profile.elyx.sha256")
    args = parser.parse_args()
    try:
        if not args.check:
            build(with_manifest=not args.no_manifest)
        digest = validate_archive()
        if args.write_sums:
            write_checksum(digest)
    except (OSError, RuntimeError, SyntaxError, zipfile.BadZipFile) as error:
        print("ERROR:", error, file=sys.stderr)
        return 1
    with zipfile.ZipFile(ARCHIVE) as package:
        files = sorted(name for name in package.namelist() if not name.endswith("/"))
    print("OK {} ({} files)".format(ARCHIVE.relative_to(REPOSITORY), len(files)))
    for name in files:
        print("   ", name)
    print("sha256", digest)
    if args.write_sums:
        print("wrote", CHECKSUM_FILE.relative_to(REPOSITORY))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
